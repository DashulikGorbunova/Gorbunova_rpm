#!/usr/bin/env python3
"""Start one local process; credentials stay in environment, not process arguments."""
import os
from pathlib import Path
import subprocess
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from app.core.config import Settings
root=Path(__file__).resolve().parents[1]
os.chdir(root)
(root/'runtime').mkdir(exist_ok=True)
base=[sys.executable,'-m','celery','-A','app.core.celery_app:celery_app']
commands={
 'delivery':[sys.executable,'delivery_server.py'],
 'worker':base+['worker','--loglevel=info','--pool=prefork','--concurrency=2','-Q','default','-E'],
 'beat':base+['beat','--loglevel=info','--schedule',str(root/'runtime/beat-schedule')],
 'flower':base+['flower','--address=127.0.0.1','--port=5555'],
 'api':[sys.executable,'-m','uvicorn','app.main:app','--host','127.0.0.1','--port','8000','--no-proxy-headers'],
}
if len(sys.argv)!=2 or sys.argv[1] not in commands:
    raise SystemExit('Usage: python scripts/run.py api|delivery|worker|beat|flower')
env=os.environ.copy()
if sys.argv[1]=='flower':
    secret=Settings().flower_basic_auth
    if secret is None:
        raise SystemExit('FLOWER_BASIC_AUTH is required, e.g. generated by init_env.py')
    env['FLOWER_BASIC_AUTH']=secret.get_secret_value()
raise SystemExit(subprocess.call(commands[sys.argv[1]],env=env))
