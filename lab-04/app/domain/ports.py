from __future__ import annotations
from datetime import datetime
from decimal import Decimal
from typing import Protocol
from app.domain.entities import User, Order, MenuItem, Delivery, AuthSession, RefreshToken

class Passwords(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, hashed: str) -> bool: ...

class TokenCodec(Protocol):
    def issue(self, user_id: int, session_id: str, expires_at: datetime) -> dict: ...
    def decode(self, token: str, kind: str) -> dict: ...
    def digest(self, token: str) -> str: ...

class UserRepository(Protocol):
    def by_email(self, email: str) -> User | None: ...
    def get(self, user_id: int) -> User | None: ...
    def create(self, email: str, password_hash: str, role: str) -> User: ...
    def list(self) -> list[User]: ...
    def update(self, user_id: int, role: str | None, blocked: bool | None) -> User: ...

class AuthRepository(Protocol):
    def by_email(self, email: str) -> User | None: ...
    def get(self, user_id: int) -> User | None: ...
    def create_session(self, user_id: int, session_id: str, expires_at: datetime) -> None: ...
    def lock_session(self, session_id: str) -> AuthSession | None: ...
    def get_session(self, session_id: str) -> AuthSession | None: ...
    def refresh(self, token_hash: str) -> RefreshToken | None: ...
    def save_refresh(self, token_hash: str, session_id: str, expires_at: datetime) -> None: ...
    def consume_refresh(self, token_hash: str) -> None: ...
    def revoke_session(self, session_id: str) -> None: ...
    def commit(self) -> None: ...

class MenuRepository(Protocol):
    def get(self, item_id: int) -> MenuItem | None: ...
    def list(self) -> list[MenuItem]: ...
    def category(self, category_id: int) -> list[MenuItem]: ...
    def create(self, name: str, price: Decimal, category_id: int = 1) -> MenuItem: ...
    def update(self, item_id: int, name: str, price: Decimal, category_id: int = 1) -> MenuItem: ...

class OrderRepository(Protocol):
    def get(self, order_id: int, lock: bool = False) -> Order | None: ...
    def item_exists(self, item_id: int) -> bool: ...
    def create(self, customer_id: int, item_id: int, quantity: int) -> Order: ...
    def list(self, customer_id: int | None = None, kitchen: bool = False) -> list[Order]: ...
    def cancel(self, order_id: int) -> Order: ...

class DeliveryRepository(Protocol):
    def get(self, delivery_id: int) -> Delivery | None: ...
    def list(self, user: User) -> list[Delivery]: ...
    def order(self, order_id: int) -> Order | None: ...
    def user(self, user_id: int) -> User | None: ...
    def create(self, order_id: int, courier_id: int) -> Delivery: ...
    def complete(self, delivery_id: int) -> Delivery: ...
